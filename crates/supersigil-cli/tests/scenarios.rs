/// Gives `f`'s repository the person's git identity.
fn identify(f: &Fixture) {
    f.git(&["config", "user.name", NAME]);
    f.git(&["config", "user.email", "ada@example.com"]);
}

/// Creates the slice fixture with the person's git identity.
/// Its gate has `old.txt`, `lines:src/lib.rs`, untracked `src/new.rs`,
/// and `gap:src/lib.rs`.
fn finished() -> Fixture {
    let f = Fixture::new();
    slice(&f);
    identify(&f);
    f
}

/// What `supersigil review <args>` prints in the repository.
fn review(f: &Fixture, args: &[&str]) -> String {
    printed(f.supersigil(
        &f.repo,
        &[&["review", "--format", "terminal"], args].concat(),
    ))
}

/// What `supersigil judge <args>` prints in the repository.
fn judge(f: &Fixture, args: &[&str]) -> String {
    printed(f.plain(
        &f.repo,
        &[&["judge", "--format", "terminal"], args].concat(),
    ))
}

/// Runs `command` and returns its standard output; panics unless it succeeds.
fn printed(mut command: Command) -> String {
    let output = command.output().unwrap();
    assert!(
        output.status.success(),
        "{}",
        String::from_utf8_lossy(&output.stderr)
    );
    String::from_utf8(output.stdout).unwrap()
}

/// Runs `supersigil judge <args>` in the repository with a Claude Code session
/// marker and piped output.
fn judge_in_agent(f: &Fixture, args: &[&str]) -> Output {
    f.plain(&f.repo, &[&["judge"], args].concat())
        .env("CLAUDECODE", "1")
        .output()
        .unwrap()
}

/// The review a summary's first line names, by the 8 digits it shows.
fn shown_review(summary: &str) -> String {
    summary
        .strip_prefix("Review ")
        .and_then(|rest| rest.get(..8))
        .unwrap_or_else(|| panic!("{summary}"))
        .to_owned()
}

/// The status lines of `summary`: from the one after the header to the gate
/// line.
fn status_lines(summary: &str) -> Vec<&str> {
    summary
        .lines()
        .skip(4)
        .take_while(|line| !line.starts_with("Gate: "))
        .collect()
}

/// Every judgment in the repository's review store, in the order recorded.
fn recorded(f: &Fixture) -> Vec<Judgment> {
    reviews::find(&f.reviews(), &f.repo.join(".git"))
        .unwrap()
        .map_or_else(Vec::new, |store| {
            store.snapshot().unwrap().judgments().unwrap()
        })
}

/// The judgment recorded last.
fn last(f: &Fixture) -> Judgment {
    recorded(f).pop().expect("a judgment")
}

/// The short commit `HEAD` names.
fn head(f: &Fixture) -> String {
    f.git(&["rev-parse", "--short=7", "HEAD"]).trim().to_owned()
}

/// The lines that say what to run next while `names` are open.
fn next(names: &str) -> String {
    format!(
        "Next: supersigil judge acknowledge {names}\n  \
         or: supersigil judge dismiss <name>... --reason <text>\n  \
         then: supersigil judge complete\n"
    )
}

/// What `supersigil annotate <args>` prints in the repository, given the
/// store options `review` passes to the skill.
fn annotate(f: &Fixture, args: &[&str]) -> String {
    printed(f.supersigil(&f.repo, &[&["annotate"], args].concat()))
}

/// The brief `annotate prepare` writes for the slice session, read back
/// from the file the skill names.
fn brief(f: &Fixture) -> Value {
    let out = f.root.join("brief.json");
    let printed = annotate(f, &["prepare", SLICE_SHORT, "--out", out.to_str().unwrap()]);
    assert_eq!(printed, "");
    serde_json::from_slice(&std::fs::read(out).unwrap()).unwrap()
}

/// The text of the slice session's turn `id`, as `brief` gives it.
fn said<'b>(brief: &'b Value, id: &str) -> &'b str {
    brief["transcripts"][0]["turns"]
        .as_array()
        .unwrap()
        .iter()
        .find(|turn| turn["id"] == id)
        .and_then(|turn| turn["text"]["value"].as_str())
        .unwrap_or_else(|| panic!("no text of turn {id} in the brief"))
}

/// An annotation of the slice session written from `brief` as the skill
/// writes one: built on its current revision and prepared from it, with a
/// decision behind the capitalised greeting explained by `rationale`, and
/// a question about the same edit.
fn annotation(brief: &Value, rationale: &Value) -> Value {
    let greet = edit_of(SLICE_SESSION, "toolu_05");
    json!({
        "schema": "supersigil.annotation/1",
        "session": brief["session"],
        "based_on": brief["current"]["revision"],
        "prepared": {
            "record": brief["record"],
            "observation_revision": brief["observation_revision"],
            "observed": brief["observed"],
        },
        "produced_by": "claude-code/supersigil-annotate",
        "decisions": [{
            "id": "d1",
            "title": "Capitalise the greeting",
            "cites": [greet],
            "rationale": rationale,
        }],
        "open_questions": [
            {"id": "q1", "text": "Should the greeting end with an exclamation mark?", "about": [greet]},
        ],
    })
}

/// Writes `document` to a file and imports it as the skill does; returns
/// what `annotate import` prints.
fn import(f: &Fixture, document: &Value) -> String {
    let file = f.root.join("annotation.json");
    std::fs::write(&file, serde_json::to_vec(document).unwrap()).unwrap();
    annotate(
        f,
        &["import", file.to_str().unwrap(), "--format", "terminal"],
    )
}

/// The slice review's JSON, as `review --format json` prints it.
fn review_json(f: &Fixture) -> Value {
    f.json(&f.repo, &["review", "--format", "json"])
}

/// Whether `review` is complete, and the revision, dispute mark and
/// corrections of the one decision it shows: each correction's judgment,
/// the revision it addressed, and whether that revision has seen it.
fn marks(review: &Value) -> Value {
    let [decision] = review["decisions"].as_array().unwrap().as_slice() else {
        panic!("{:#}", review["decisions"]);
    };
    let corrections: Vec<Value> = decision["corrections"]
        .as_array()
        .unwrap()
        .iter()
        .map(|correction| {
            json!({"judgment": correction["judgment"], "addressed": correction["addressed"],
                "seen": correction["seen"]})
        })
        .collect();
    json!({
        "complete": review["status"]["complete"],
        "revision": decision["revision"],
        "disputed": decision["disputed"],
        "corrections": corrections,
    })
}

/// Judges the slice fixture's gate as scenario 1 does and completes the
/// review; returns the acknowledgment, the dismissal, and the completion,
/// each stamped when it was recorded.
fn complete(f: &Fixture) -> [Judgment; 3] {
    judge(f, &["ack", "old.txt", "lines:src/lib.rs", "gap:src/lib.rs"]);
    judge(f, &["dismiss", "src/new.rs", "--reason", GENERATED]);
    judge(f, &["complete"]);
    <[Judgment; 3]>::try_from(recorded(f)).unwrap()
}

#[test]
fn scenario_1_review_acknowledge_dismiss_comment_and_complete() {
    let f = finished();
    let head = head(&f);

    let summary = review(&f, &[]);

    let id8 = shown_review(&summary);
    assert!(
        summary.starts_with(&format!("Review {id8}: working tree over {head}.\n")),
        "{summary}"
    );
    assert!(
        summary.contains(
            "\nReview not complete.\nGate: 4 open, 0 closed.\n\n  \
             old.txt           open  1 unexplained line: 1 unattributed\n  \
             lines:src/lib.rs  open  4 unexplained lines: 4 unattributed\n  \
             src/new.rs        open  untracked, a recorded edit names it; not included\n  \
             gap:src/lib.rs    open  1 gap between recorded edits\n"
        ),
        "{summary}"
    );
    assert!(
        summary.ends_with(&format!(
            "\n\n{}",
            next("old.txt lines:src/lib.rs src/new.rs gap:src/lib.rs")
        )),
        "{summary}"
    );

    // Items named as the gate prints them, several in one call.
    let acknowledged = judge(
        &f,
        &["ack", "old.txt", "lines:src/lib.rs", "gap:src/lib.rs"],
    );
    assert_eq!(
        acknowledged,
        format!(
            "Acknowledged old.txt, lines:src/lib.rs, and gap:src/lib.rs on review {id8} \
             (working tree over {head}).\n\
             Kept the reviewed snapshot as refs/supersigil/reviews/{id8}…\n\
             Judgment {}. Gate: 1 open: src/new.rs.\n{}",
            last(&f).id.short(),
            next("src/new.rs")
        )
    );

    let acknowledgment = last(&f);
    let dismissed = judge(&f, &["dismiss", "src/new.rs", "--reason", GENERATED]);
    let dismissal = last(&f);
    assert_eq!(
        dismissed,
        format!(
            "Dismissed src/new.rs on review {id8} (working tree over {head}).\n\
             The file stays outside the review; to review its content, run supersigil review \
             --include-untracked=src/new.rs.\n\
             Judgment {}. Gate: 0 open. Review not yet complete.\n\
             Next: supersigil judge complete\n",
            last(&f).id.short()
        )
    );

    let commented = judge(
        &f,
        &["comment", "--text", "Checked greet against its callers."],
    );
    assert_eq!(
        commented,
        format!(
            "Commented on review {id8} (working tree over {head}).\n\
             Judgment {}. Gate: 0 open. Review not yet complete.\n\
             Next: supersigil judge complete\n",
            last(&f).id.short()
        )
    );

    let completed = judge(&f, &["complete"]);
    let completion = last(&f);
    assert_eq!(
        completed,
        format!(
            "Completed review {id8} (working tree over {head}).\n\
             Judgment {}. Gate: 0 open. Review complete.\n",
            completion.id.short()
        )
    );

    // Reviewing again finds the same review, complete.
    let again = review(&f, &[]);
    let date = completion.at.date();
    let (acked, dismissed_on) = (acknowledgment.at.date(), dismissal.at.date());
    assert_eq!(shown_review(&again), id8);
    assert!(
        again.contains(&format!(
            "\nReview complete: completed on {date} by {NAME}.\nGate: 0 open, 4 closed.\n\n  \
             old.txt           acknowledged  by {NAME} on {acked}\n  \
             lines:src/lib.rs  acknowledged  by {NAME} on {acked}\n  \
             src/new.rs        dismissed     by {NAME} on {dismissed_on}\n  \
             gap:src/lib.rs    acknowledged  by {NAME} on {acked}\n"
        )),
        "{again}"
    );
    assert!(!again.contains("Next:"), "{again}");
}

#[test]
fn scenario_2_eighty_files_with_unexplained_lines_are_judged_in_one_call() {
    let f = Fixture::new();
    identify(&f);
    let names: Vec<String> = (0..80)
        .map(|i| format!("snapshots/case{i:02}.txt"))
        .collect();
    for name in &names {
        write(&f.repo, name, "expected\n");
    }
    f.commit(&f.repo, "base");
    // Regenerated by a command no transcript records: no line is explained.
    for name in &names {
        write(&f.repo, name, "regenerated\n");
    }

    let summary = review(&f, &[]);

    let rows: Vec<String> = names
        .iter()
        .map(|name| format!("  {name}  open  2 unexplained lines: 2 unattributed"))
        .collect();
    assert!(
        summary.contains(&format!(
            "\nGate: 80 open, 0 closed.\n\n{}\n\nfiles:\n",
            rows.join("\n")
        )),
        "{summary}"
    );
    // The next command leaves the 80 names to the rows above it, so it
    // stays short enough for a command line, and the summary suggests a
    // pager.
    let next = summary
        .lines()
        .find_map(|line| line.strip_prefix("Next: supersigil "))
        .unwrap_or_else(|| panic!("{summary}"));
    assert_eq!(
        next,
        "judge acknowledge <name>... (80 open items, listed above)"
    );
    assert!(
        summary.ends_with(
            "\nLong output: run the same review command with --format terminal and pipe it to \
             less.\n"
        ),
        "{summary}"
    );

    // The names as the rows list them, acknowledged in one call with one
    // shared reason.
    let listed: Vec<&str> = summary
        .lines()
        .filter_map(|line| {
            line.strip_prefix("  ")?
                .strip_suffix("  open  2 unexplained lines: 2 unattributed")
        })
        .collect();
    assert_eq!(listed, names);
    let reason = "regenerated snapshots, read in the diff";
    let acknowledged = judge(
        &f,
        &[&["acknowledge"], listed.as_slice(), &["--reason", reason]].concat(),
    );
    let completed = judge(&f, &["complete"]);

    let [acknowledgment, completion] = <[Judgment; 2]>::try_from(recorded(&f)).unwrap();
    assert_eq!(acknowledgment.items.len(), 80);
    assert_eq!(acknowledgment.reason.as_deref(), Some(reason));
    assert!(
        acknowledged.ends_with(&format!(
            "\nJudgment {}. Gate: 0 open. Review not yet complete.\nNext: supersigil judge \
             complete\n",
            acknowledgment.id.short()
        )),
        "{acknowledged}"
    );
    assert!(
        completed.ends_with(&format!(
            "\nJudgment {}. Gate: 0 open. Review complete.\n",
            completion.id.short()
        )),
        "{completed}"
    );
}

#[test]
fn scenario_3_a_file_the_agent_changes_after_completion_is_reported_and_judged_again() {
    let f = finished();
    let id8 = shown_review(&review(&f, &[]));
    let [acknowledgment, dismissal, completion] = complete(&f);
    // The agent changes `src/lib.rs` again, in a recorded edit.
    let lib = f.repo.join("src/lib.rs");
    let appended = Session::new(SLICE_SESSION, &f.repo)
        .prompt("Greet more warmly.")
        .edit(
            "toolu_warm",
            &lib,
            LIB_FINAL,
            "Hello, {name}!",
            "Welcome, {name}!",
        )
        .text();
    f.transcript(
        &f.repo,
        "slice.jsonl",
        &format!("{}{appended}", slice_text()),
    );
    write(
        &f.repo,
        "src/lib.rs",
        &LIB_FINAL.replace("Hello, {name}!", "Welcome, {name}!"),
    );

    let summary = review(&f, &[]);

    let date = completion.at.date();
    let since = format!("since your completion on {date} (review {id8})");
    assert_eq!(
        status_lines(&summary),
        [
            format!("Review not complete. Code changed {since}:"),
            "  src/lib.rs".to_owned(),
            format!("Evidence changed {since}:"),
            format!("  new: session {SLICE_SESSION}: src/lib.rs"),
        ],
        "{summary}"
    );
    // The new edit explains the line it changed, so the edits behind the
    // lines still unexplained are the same.
    let carried = |judgment: &Judgment| {
        format!(
            "carried from review {id8}, by {NAME} on {}",
            judgment.at.date()
        )
    };
    assert!(
        summary.contains(&format!(
            "\nGate: 1 open, 3 closed.\n\n  \
             old.txt           acknowledged  {ack}\n  \
             lines:src/lib.rs  reopened      file content or mode changed; line explanations \
             changed since your acknowledgment\n  \
             src/new.rs        dismissed     {dismissed}\n  \
             gap:src/lib.rs    acknowledged  {ack}\n",
            ack = carried(&acknowledgment),
            dismissed = carried(&dismissal)
        )),
        "{summary}"
    );
    assert!(
        summary.ends_with(&format!("\n\n{}", next("lines:src/lib.rs"))),
        "{summary}"
    );

    // The person reads the change, judges the reopened item, and completes
    // the new review.
    judge(
        &f,
        &["ack", "lines:src/lib.rs", "--reason", "the warmer greeting"],
    );
    judge(&f, &["complete"]);
    let again = review(&f, &[]);

    assert_eq!(
        status_lines(&again),
        [format!(
            "Review complete: completed on {} by {NAME}.",
            last(&f).at.date()
        )],
        "{again}"
    );
}

#[test]
fn scenario_4_the_reviewed_working_tree_committed_is_reviewed_as_a_commit() {
    let f = finished();
    let id8 = shown_review(&review(&f, &[]));
    let [acknowledgment, _, completion] = complete(&f);
    // The person commits what they reviewed; untracked `src/new.rs` stays
    // out of the commit.
    f.git(&["commit", "-qam", "Add greet"]);

    // The working tree now holds no change in scope: the summary points at
    // the commit just made.
    let working_tree = review(&f, &[]);
    let commit = review(&f, &["--target", "HEAD"]);

    assert!(
        working_tree.contains(&format!(
            "\nfiles:\n  no changes in scope; to review a commit just made, run supersigil \
             review --target HEAD {}\n",
            f.claude_flag()
        )),
        "{working_tree}"
    );
    let date = completion.at.date();
    assert_eq!(
        status_lines(&commit),
        [format!(
            "Review complete: completed on {date} by {NAME} for the same content (review {id8})."
        )],
        "{commit}"
    );
    let carried = format!(
        "acknowledged  carried from review {id8}, by {NAME} on {}",
        acknowledgment.at.date()
    );
    assert!(
        commit.contains(&format!(
            "\nGate: 0 open, 3 closed.\n\n  \
             old.txt           {carried}\n  \
             lines:src/lib.rs  {carried}\n  \
             gap:src/lib.rs    {carried}\n"
        )),
        "{commit}"
    );
    assert!(!commit.contains("Next:"), "{commit}");
}

